import fs from 'node:fs';

const lin = c => (c /= 255) <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
const gam = c => 255 * (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const W = [0.95047, 1, 1.08883];
const f = t => t > 216 / 24389 ? Math.cbrt(t) : (24389 / 27 * t + 16) / 116;
const fi = t => t ** 3 > 216 / 24389 ? t ** 3 : (116 * t - 16) / (24389 / 27);

const hexToLch = hex => {
  const [r, g, b] = [1, 3, 5].map(i => lin(parseInt(hex.slice(i, i + 2), 16)));
  const xyz = [0.4124 * r + 0.3576 * g + 0.1805 * b, 0.2126 * r + 0.7152 * g + 0.0722 * b, 0.0193 * r + 0.1192 * g + 0.9505 * b].map((v, i) => f(v / W[i]));
  const L = 116 * xyz[1] - 16, a = 500 * (xyz[0] - xyz[1]), bb = 200 * (xyz[1] - xyz[2]);
  return { L, C: Math.hypot(a, bb), h: (Math.atan2(bb, a) * 180 / Math.PI + 360) % 360 };
};
const lchToRgb = (L, C, h) => {
  const a = C * Math.cos(h * Math.PI / 180), b = C * Math.sin(h * Math.PI / 180);
  const fy = (L + 16) / 116, fx = fy + a / 500, fz = fy - b / 200;
  const [x, y, z] = [fi(fx) * W[0], fi(fy), fi(fz) * W[2]];
  return [3.2406 * x - 1.5372 * y - 0.4986 * z, -0.9689 * x + 1.8758 * y + 0.0415 * z, 0.0557 * x - 0.204 * y + 1.057 * z];
};
const tone = (pal, t) => {
  let c = pal.C, rgb;
  for (; c >= 0; c -= 0.5) { rgb = lchToRgb(t, c, pal.h); if (rgb.every(v => v >= -0.0005 && v <= 1.0005)) break; }
  return '#' + rgb.map(v => Math.round(Math.min(255, Math.max(0, gam(Math.min(1, Math.max(0, v)))))).toString(16).padStart(2, '0')).join('').toUpperCase();
};
const pal = (hex, chroma) => { const l = hexToLch(hex); return { h: l.h, C: chroma ?? l.C }; };

